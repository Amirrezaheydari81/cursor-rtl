'use strict';

/**
 * @typedef {object} RtlOptions
 * @property {'rtl' | 'auto'} direction
 * @property {string} fontFamily
 * @property {number} fontSize
 * @property {number} lineHeight
 * @property {boolean} fontInInput
 * @property {string} customCss
 */

const GENERIC_FAMILIES = new Set([
  'serif', 'sans-serif', 'monospace', 'cursive', 'fantasy',
  'system-ui', 'ui-sans-serif', 'ui-serif', 'ui-monospace', 'ui-rounded',
]);

const MESSAGE_SELECTORS = [
  '.markdown-root',
  '.anysphere-markdown-container-root',
  '.markdown-section',
  '.composer-message-group',
  '[data-message-kind="assistant"] .markdown-root',
  '.space-y-4',
];

const INPUT_SELECTORS = [
  '.aislash-editor-input',
  '.aislash-editor-input-readonly',
  '.composer-human-message',
  '.composer-human-message-container',
  '.human-message-with-todos-wrapper',
];

const PLACEHOLDER_SELECTORS = [
  '.aislash-editor-placeholder',
  '[data-placeholder]',
];

const LIST_SELECTORS = [
  '.markdown-root ul',
  '.markdown-root ol',
  '.markdown-section ul',
  '.markdown-section ol',
  '.list-disc',
  '.list-inside',
  '[data-streamdown="unordered-list"]',
  '[data-streamdown="ordered-list"]',
];

const CODE_SELECTORS = [
  'code',
  'pre',
  '.markdown-code-outer-container',
  '.cursor-code-block-content',
  '.composer-code-block-content',
  '.monaco-editor',
  '.ui-code-block',
  '.ui-default-code',
  '.composer-message-codeblock',
];

const MISC_SELECTORS = [
  '.todo-list-container',
  '.ui-todo-item__content',
  '.todo-label',
  '.todo-content',
  '#composer-toolbar-section',
  '.composer-questionnaire-toolbar',
  '.composer-questionnaire-toolbar-header',
  '.composer-questionnaire-toolbar-question-label',
  '.composer-questionnaire-toolbar-option',
  '.composer-questionnaire-toolbar-freeform-input',
  '.composer-questionnaire-toolbar-actions',
  '.ui-step-group-header',
  '.ui-collapsible-header',
  '.composer-tool-former-message',
  '.tool-summary-hover-target',
  '.truncate-one-line',
];

const FONT_TEXT_SELECTORS = [
  '.markdown-root',
  '.anysphere-markdown-container-root',
  '.markdown-section',
  '.composer-human-message',
  '.ui-todo-item__content',
  '.todo-content',
  '.composer-questionnaire-toolbar',
];

const FONT_INPUT_SELECTORS = [
  '.aislash-editor-input',
  '.aislash-editor-input-readonly',
  '.aislash-editor-placeholder',
];

/**
 * Turns a user-supplied family list ("Vazirmatn, Tahoma") into a safe CSS value.
 * @param {string} input
 * @returns {string}
 */
function toFontFamilyValue(input) {
  const families = input
    .split(',')
    .map((name) => name.trim().replace(/^["']|["']$/g, '').replace(/[;{}<>\\"]/g, ''))
    .filter(Boolean)
    .map((name) => (GENERIC_FAMILIES.has(name.toLowerCase()) ? name : `"${name}"`));
  return families.length ? `${families.join(', ')}, system-ui, sans-serif` : '';
}

/**
 * @param {string[]} selectors
 * @param {string[]} declarations
 */
function rule(selectors, declarations) {
  return `${selectors.join(',\n')} {\n${declarations.map((d) => `  ${d} !important;`).join('\n')}\n}\n`;
}

/**
 * @param {RtlOptions} options
 * @returns {string}
 */
function buildCss(options) {
  const rtl = options.direction !== 'auto';
  const dir = rtl
    ? ['direction: rtl', 'text-align: right']
    : ['unicode-bidi: plaintext', 'text-align: start'];

  const parts = ['/* Generated by the Cursor RTL extension. Do not edit; change the extension settings instead. */\n'];

  parts.push(rule([...MESSAGE_SELECTORS, ...INPUT_SELECTORS, ...MISC_SELECTORS], dir));

  parts.push(rule(PLACEHOLDER_SELECTORS, rtl
    ? [...dir, 'right: 15px', 'left: auto']
    : dir));

  parts.push(rule(LIST_SELECTORS, rtl
    ? [...dir, 'padding-right: 20px', 'padding-left: 0']
    : [...dir, 'padding-inline-start: 20px']));

  parts.push(rule(['.markdown-table-container'], [
    'direction: ltr', 'overflow-x: auto', 'max-width: 100%', 'display: block', 'border-radius: 4px',
  ]));
  parts.push(rule(['table.markdown-table'], [
    ...(rtl ? ['direction: rtl'] : []), 'width: max-content', 'min-width: 100%', 'border-collapse: collapse',
  ]));
  parts.push(rule(['.markdown-table th', '.markdown-table td'], [
    ...(rtl ? ['text-align: right'] : ['unicode-bidi: plaintext', 'text-align: start']),
    'border: 1px solid var(--vscode-textSeparator-foreground)',
    'padding: 6px 10px',
  ]));

  parts.push(rule(CODE_SELECTORS, ['direction: ltr', 'text-align: left', 'unicode-bidi: plaintext']));
  parts.push('.markdown-root code,\n.markdown-section code {\n  display: inline-block;\n  direction: ltr;\n}\n');

  if (rtl) {
    parts.push(rule(['.todo-list-header', '.todo-list-header-left', '.todo-list-header-right'], [
      'direction: rtl', 'display: flex', 'flex-direction: row',
    ]));
    parts.push(rule(['.ui-todo-list', '.todo-list'], ['direction: rtl', 'padding-right: 20px', 'padding-left: 0']));
    parts.push(rule(['.ui-todo-item', '.ui-todo-item__label'], [
      'direction: rtl', 'text-align: right', 'display: flex', 'align-items: flex-start',
    ]));
    parts.push(rule(['.ui-todo-item__indicator'], ['margin-left: 8px', 'margin-right: 0', 'margin-top: 2px']));
    parts.push(rule(['.todo-indicator-container'], ['margin-left: 8px', 'margin-right: 0']));
    parts.push(rule(['.composer-questionnaire-toolbar-option-label'], ['margin-right: 8px', 'margin-left: 0']));
    parts.push(rule(['.composer-pane-controls-feedback'], ['direction: rtl']));
  }
  parts.push(rule(['.ui-todo-item__content'], ['unicode-bidi: plaintext']));

  const fontSelectors = options.fontInInput
    ? [...FONT_TEXT_SELECTORS, ...FONT_INPUT_SELECTORS]
    : FONT_TEXT_SELECTORS;
  const fontDeclarations = [];
  const family = toFontFamilyValue(options.fontFamily);
  if (family) fontDeclarations.push(`font-family: ${family}`);
  if (options.fontSize > 0) fontDeclarations.push(`font-size: ${options.fontSize}px`);
  if (options.lineHeight > 0) fontDeclarations.push(`line-height: ${options.lineHeight}`);
  if (fontDeclarations.length) {
    parts.push(rule(fontSelectors, fontDeclarations));
    parts.push(rule(
      fontSelectors.flatMap((s) => [`${s} code`, `${s} pre`]),
      ['font-family: var(--vscode-editor-font-family), monospace'],
    ));
  }

  if (options.customCss.trim()) {
    parts.push(`/* Custom CSS */\n${options.customCss.trim()}\n`);
  }

  return parts.join('\n');
}

module.exports = { buildCss };
